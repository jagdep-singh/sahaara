import 'dotenv/config';

import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { prisma } from '../lib/db';

function list(items: string[]) {
  return items.length ? items.map((item) => `- ${item}`).join('\n') : '-';
}

async function main() {
  const [contents, campaigns, centres] = await Promise.all([
    prisma.schemeContent.findMany({
      where: { lang: 'hi' },
      include: {
        scheme: {
          select: {
            code: true,
            slug: true,
            need: true,
            publishedAt: true,
          },
        },
      },
    }),
    prisma.campaign.findMany({ orderBy: { slug: 'asc' } }),
    prisma.helpCentre.findMany({ orderBy: [{ district: 'asc' }, { name: 'asc' }] }),
  ]);

  contents.sort((a, b) => a.scheme.code.localeCompare(b.scheme.code));

  const lines: string[] = [
    '# Hindi review',
    '',
    'Generated from the seeded database. Proofread the Hindi below and send corrections back.',
    'Do not edit this file as the source of truth; corrections go into `i18n/hi.ts` and `prisma/seed-data.ts` / `prisma/seed.ts`.',
    '',
    `Generated: ${new Date().toISOString()}`,
    '',
    '## Schemes',
    '',
  ];

  for (const content of contents) {
    lines.push(
      `### ${content.scheme.code} — ${content.title}`,
      '',
      `- Slug: \`${content.scheme.slug}\``,
      `- Need: ${content.scheme.need}`,
      `- Status: ${content.status}`,
      `- Published: ${content.scheme.publishedAt ? 'yes' : 'no'}`,
      `- Origin: ${content.origin}`,
      '',
      '**Benefit**',
      '',
      content.benefit,
      '',
      '**Who can apply**',
      '',
      content.whoCanApply,
      '',
      '**Documents**',
      '',
      list(content.documents),
      '',
      '**How to apply**',
      '',
      content.howToApply,
      '',
    );
  }

  lines.push('## Campaigns', '');
  for (const campaign of campaigns) {
    lines.push(
      `### ${campaign.slug}`,
      '',
      `- Title (Hindi): ${campaign.titleHi}`,
      `- Description (Hindi): ${campaign.descriptionHi ?? '-'}`,
      '',
    );
  }

  lines.push('## Help centres', '');
  for (const centre of centres) {
    lines.push(
      `- ${centre.district}: ${centre.name} — ${centre.address} — ${centre.phone}`,
    );
  }
  lines.push('');

  const output = path.join(process.cwd(), 'docs', 'HINDI-REVIEW.md');
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, lines.join('\n'), 'utf8');
  console.log(`Wrote ${output}`);
}

main()
  .then(async () => {
    await prisma.$disconnect();
  })
  .catch(async (error) => {
    console.error(error);
    await prisma.$disconnect();
    process.exit(1);
  });
